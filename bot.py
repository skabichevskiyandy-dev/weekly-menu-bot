DAYS = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье"]

def calculate_total_price(ingredients):
    totals = {}
    for store in ["Пятёрочка", "Магнит", "Перекрёсток", "Чижик"]:
        totals[store] = sum(PRICES.get(ing, {}).get(store, 0) for ing in ingredients)
    return totals

@bot.message_handler(commands=['start'])
def send_welcome(message):
    bot.reply_to(message, "Привет! Напиши /menu — и я пришлю меню на неделю.")

@bot.message_handler(commands=['menu'])
def send_menu(message):
    selected = [random.choice(list(RECIPES.keys())) for _ in range(7)]
    all_ings = set()
    text = "🍽 *Меню на неделю:*\n\n"
    for i, day in enumerate(DAYS):
        r = RECIPES[selected[i]]
        all_ings.update(r["ингредиенты"])
        text += f"*{day}:* {selected[i]}\n🔥 {r['калории']} ккал\n📝 {r['описание']}\n\n"
    prices = calculate_total_price(all_ings)
    text += "💰 *Стоимость продуктов (всё меню):*\n"
    for store, price in prices.items():
        text += f"{store}: {price:.2f} ₽\n"
    bot.send_message(message.chat.id, text, parse_mode="Markdown")

